    fun random(mode:ChallengeMode,seed:Int):Genre {
        val r=Random(seed)
        return when(mode){
            ChallengeMode.RARE_GENRE -> rare.random(r)
            ChallengeMode.HYBRID -> hybrids.random(r)
            else -> common.random(r)
        }
    }
    fun all():List<Genre>=common+rare+hybrids
